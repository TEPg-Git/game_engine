// ============================================================
// TRANSFORM
// ============================================================

#[derive(Clone, Copy, Debug)]
pub struct Transform {
    // POSITION
    pub position: [f32; 2],

    // ROTATION
    // Stored in radians.
    pub rotation: f32,

    // SCALE
    pub scale: [f32; 2],
}

// ============================================================
// IMPLEMENTATION
// ============================================================

impl Transform {
    // ========================================================
    // DEFAULT TRANSFORM
    // ========================================================

    pub fn new() -> Self {
        Self {
            position: [0.0, 0.0],

            rotation: 0.0,

            scale: [1.0, 1.0],
        }
    }

    // ========================================================
    // TRANSLATE
    // ========================================================

    pub fn translate(&mut self, x: f32, y: f32) {
        self.position[0] += x;
        self.position[1] += y;
    }

    // ========================================================
    // ROTATE
    // ========================================================

    pub fn rotate(&mut self, radians: f32) {
        self.rotation += radians;
    }

    // ========================================================
    // SET SCALE
    // ========================================================

    pub fn set_scale(&mut self, x: f32, y: f32) {
        self.scale = [x, y];
    }
}
