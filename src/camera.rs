// ============================================================
// CAMERA
// ============================================================

pub struct Camera {
    // ========================================================
    // POSITION
    // ========================================================

    pub position: [f32; 2],

    // ========================================================
    // ZOOM
    // ========================================================

    pub zoom: f32,
}

// ============================================================
// IMPLEMENTATION
// ============================================================

impl Camera {
    // ========================================================
    // DEFAULT CAMERA
    // ========================================================

    pub fn new() -> Self {
        Self {
            position: [0.0, 0.0],

            zoom: 1.0,
        }
    }

    // ========================================================
    // MOVE
    // ========================================================

    pub fn translate(&mut self, x: f32, y: f32) {
        self.position[0] += x;

        self.position[1] += y;
    }

    // ========================================================
    // SET POSITION
    // ========================================================

    pub fn set_position(&mut self, x: f32, y: f32) {
        self.position = [x, y];
    }

    // ========================================================
    // SET ZOOM
    // ========================================================

    pub fn set_zoom(&mut self, zoom: f32) {
        self.zoom = zoom.max(0.01);
    }
}
